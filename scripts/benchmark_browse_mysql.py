"""Repeatable, local-only Browse service baseline without content in its report.

Read cases from JSON rather than embedding account/deck IDs. Each sample uses a
fresh Flask context/session. Only SELECT and optional EXPLAIN are allowed while
the service runs; the audit factory disables startup mutators. No schema setup.
"""

from __future__ import annotations

import argparse
from collections import Counter
from contextlib import ExitStack
from datetime import datetime, timezone
import hashlib
import json
import math
from pathlib import Path
import re
import statistics
import sys
import time
from unittest.mock import patch
from zoneinfo import ZoneInfo

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

OPERATIONS = {"cards", "decks", "note_types", "notes", "note_decks"}
QUERY_KEYS = {"deck_id", "include_subdecks", "all_templates", "q", "tag", "status", "sort_by", "sort_dir", "page", "per_page"}


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=False,
                                    separators=(",", ":")).encode("utf-8")).hexdigest()


def load_cases(path):
    cases = json.loads(Path(path).read_text(encoding="utf-8-sig"))
    if not isinstance(cases, list) or not cases:
        raise ValueError("Cases must be a nonempty JSON list.")
    names = set()
    for case in cases:
        if not isinstance(case, dict) or set(case) - {"name", "user_id", "operation", "admin_mode", "timezone", "query", "compact"}:
            raise ValueError("Unknown case properties.")
        if not isinstance(case.get("name"), str) or not case["name"] or case["name"] in names:
            raise ValueError("Case names must be nonempty and unique.")
        names.add(case["name"])
        if type(case.get("user_id")) is not int or case["user_id"] <= 0:
            raise ValueError("Each case requires a positive integer user_id.")
        if case.get("operation", "cards") not in OPERATIONS:
            raise ValueError("Unknown Browse operation.")
        for key in ("admin_mode", "compact"):
            if key in case and type(case[key]) is not bool:
                raise ValueError(f"{key} must be a boolean.")
        query = case.get("query", {})
        if not isinstance(query, dict) or set(query) - QUERY_KEYS:
            raise ValueError("Unknown Browse query properties.")
        if any(type(value) not in (str, int, bool) for value in query.values()):
            raise ValueError("Browse query values must be strings, integers or booleans.")
        ZoneInfo(case.get("timezone", "UTC"))
    return cases


def require_read_sql(statement):
    # Statements are generated by the application, never supplied by cases.
    cte = bool(re.match(r"^\s*WITH\b", statement, re.I))
    cte_writes = re.search(r"\b(INSERT|UPDATE|DELETE|CREATE|DROP|ALTER|TRUNCATE|CALL|SET|GRANT|REVOKE|LOAD)\b|\bREPLACE\b(?!\s*\()",
        re.sub(r"\bFOR\s+UPDATE\b", "", statement, flags=re.I), re.I) if cte else False
    if (not re.match(r"^\s*(SELECT|EXPLAIN|WITH)\b", statement, re.I) or cte_writes
            or ';' in statement or re.search(
        r"\b(INTO\s+(OUTFILE|DUMPFILE)|GET_LOCK\s*\(|RELEASE_LOCK\s*\()", statement, re.I
    )):
        raise RuntimeError("Benchmark refused a non-read statement.")


def compare_reports(previous, current):
    """Require complete successful samples; equal errors cannot prove parity."""
    old = {case["name"]: case for case in previous["cases"]}
    new = {case["name"]: case for case in current["cases"]}
    if set(old) != set(new) or previous["as_of_utc"] != current["as_of_utc"]:
        return {"equivalent": False, "reason": "case-set-or-clock-mismatch"}
    mismatches = []
    for name, case in new.items():
        prior = old[name]
        samples = prior["samples"] + case["samples"]
        if (prior["input_sha256"] != case["input_sha256"]
                or any("error_type" in sample for sample in samples)
                or len({sample["payload_sha256"] for sample in samples}) != 1):
            mismatches.append(name)
    return {"equivalent": not mismatches, "mismatched_or_incomplete_cases": mismatches}


def plan_summary(plan):
    tables, flags = Counter(), Counter()
    def walk(value):
        if isinstance(value, dict):
            if "table_name" in value:
                tables[(value["table_name"], value.get("access_type"), value.get("key"))] += 1
            for flag in ("using_filesort", "using_temporary_table"):
                flags[flag] += bool(value.get(flag))
            for child in value.values():
                walk(child)
        elif isinstance(value, list):
            for child in value:
                walk(child)
    walk(plan)
    return {"table_access_nodes": [{"table": key[0], "access": key[1], "key": key[2], "plan_nodes": count}
                                   for key, count in tables.items()], "flags": dict(flags)}


def sample(app, case, options):
    from sqlalchemy import event, text
    from flask_sqlalchemy.query import Query
    from app.repositories import browse_card_repository, browse_note_repository, vocabulary_repository
    from app.repositories import flashcards_share_repository
    from app.services import browse_card_service, browse_note_service, deck_release_service, flashcard_content_service
    from models import db

    sql, phases = [], {}
    def timed(label, function):
        def call(*args, **kwargs):
            started = time.perf_counter()
            try:
                return function(*args, **kwargs)
            finally:
                phase = phases.setdefault(label, {"calls": 0, "elapsed_ms": 0})
                phase["calls"] += 1
                phase["elapsed_ms"] += (time.perf_counter() - started) * 1000
        return call

    def before(_conn, _cursor, statement, _parameters, context, _many):
        require_read_sql(statement)
        context.browse_started = time.perf_counter()

    def record(statement, parameters, context, failed=False):
        sql.append((statement, parameters, (time.perf_counter() - context.browse_started) * 1000, failed))

    def after(_conn, _cursor, statement, parameters, context, _many):
        record(statement, parameters, context)

    def failed(context):
        if context.execution_context is not None and hasattr(context.execution_context, "browse_started"):
            record(context.statement, context.parameters, context.execution_context, True)

    result = {}
    # Never retain request-scoped ORM objects across samples (including g caches).
    with app.app_context(), app.test_request_context("/api/browse/cards"), ExitStack() as stack:
        engine = db.engine
        db.session.execute(text(f"SET SESSION MAX_EXECUTION_TIME={options.max_statement_ms}"))
        db.session.execute(text(f"SET SESSION innodb_lock_wait_timeout={options.lock_wait_seconds}"))
        for module in (browse_card_service, vocabulary_repository):
            stack.enter_context(patch.object(module, "_utcnow", return_value=options.as_of))
        for owner, name, label in (
            (vocabulary_repository, "collect_accessible_browse_decks", "scope"),
            (browse_card_repository, "count_distinct_cards", "count"),
            (browse_note_repository, "count_notes", "note_count"),
            (Query, "paginate", "page_and_hydrate"),
            (browse_card_service, "load_study_authority_card_reads", "authority"),
            (browse_card_service, "aggregate_deck_study_counts", "deck_aggregate"),
            (deck_release_service, "get_note_values_for_ids_at_release", "release_values"),
            (flashcards_share_repository, "get_clone_note_field_overrides_batch", "overrides"),
            (browse_card_service, "_clone_overlay_fields", "overlay_format"),
        ):
            stack.enter_context(patch.object(owner, name, timed(label, getattr(owner, name))))
        for name, callback in (("before_cursor_execute", before), ("after_cursor_execute", after), ("handle_error", failed)):
            event.listen(engine, name, callback)
            stack.callback(event.remove, engine, name, callback)
        started = time.perf_counter()
        try:
            common = {"user_id": case["user_id"], "admin_mode": case.get("admin_mode", False), "timezone_name": case.get("timezone", "UTC")}
            operation = case.get("operation", "cards")
            if operation == "cards":
                payload = browse_card_service.list_browse_cards(**common, query_args=case.get("query", {}))
            elif operation == "notes":
                payload = browse_note_service.list_notes(**common, query_args=case.get("query", {}))
            elif operation == "note_decks":
                payload = browse_note_service.build_decks(**common)
            elif operation == "decks":
                payload = browse_card_service.build_browse_decks(**common)
            else:
                payload = flashcard_content_service.list_note_types(user_id=case["user_id"], compact=case.get("compact", False))
            encoded = timed("serialization", lambda: json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8"))()
            result.update(payload_sha256=hashlib.sha256(encoded).hexdigest(), payload_bytes=len(encoded),
                          returned=len(payload.get("items", payload.get("decks", []))),
                          **{key: payload[key] for key in ("total", "page", "pages", "has_next") if key in payload})
        except Exception as exc:
            # Exception messages can contain SQL parameters or application content.
            result.update(error_type=type(exc).__name__)
            original = getattr(exc, "orig", None)
            if original is not None and original.args and type(original.args[0]) is int:
                result["database_error_number"] = original.args[0]
            elif isinstance(getattr(exc, "code", None), str):
                result["error_code"] = exc.code
        result["elapsed_ms"] = round((time.perf_counter() - started) * 1000, 3)
        # Remove listeners/patches before diagnostic EXPLAIN; its time is excluded.
        stack.close()
        result.update(statements=len(sql), cursor_execute_ms=round(sum(row[2] for row in sql), 3),
                      locking_statements=sum(bool(re.search(r"FOR UPDATE|LOCK IN SHARE MODE|FOR SHARE", row[0], re.I)) for row in sql),
                      phases={key: {**value, "elapsed_ms": round(value["elapsed_ms"], 3)} for key, value in phases.items()})
        result["slowest"] = []
        for statement, parameters, elapsed, failure in sorted(sql, key=lambda row: row[2], reverse=True)[:3]:
            item = {"cursor_execute_ms": round(elapsed, 3), "sql_chars": len(statement), "failed": failure,
                    "count_distinct": bool(re.search(r"count\(distinct", statement, re.I)),
                    "window": "row_number()" in statement.lower()}
            if options.explain:
                try:
                    # No SQL text, predicates or bound parameters enter the report.
                    plan = db.session.connection().exec_driver_sql("EXPLAIN FORMAT=JSON " + statement, parameters).scalar()
                    item["plan"] = plan_summary(json.loads(plan))
                except Exception as exc:
                    item["explain_error_type"] = type(exc).__name__
            result["slowest"].append(item)
        db.session.rollback()
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cases", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--compare", type=Path)
    parser.add_argument("--as-of", help="Freeze UTC service clock (ISO 8601); reuse baseline clock when comparing.")
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--warmup", type=int, default=0)
    parser.add_argument("--max-statement-ms", type=int, default=5000)
    parser.add_argument("--lock-wait-seconds", type=int, default=2)
    parser.add_argument("--explain", action="store_true")
    options = parser.parse_args(argv)
    if options.repeat < 1 or options.warmup < 0 or options.max_statement_ms < 1 or options.lock_wait_seconds < 1:
        parser.error("Repetitions/time limits must be positive; warmup must be nonnegative.")
    if options.output.resolve() in {path.resolve() for path in (options.cases, options.compare) if path is not None}:
        parser.error("Output must not overwrite cases or the comparison baseline.")
    cases = load_cases(options.cases)
    previous = json.loads(options.compare.read_text(encoding="utf-8")) if options.compare else None
    clock = options.as_of or (previous["as_of_utc"] if previous else datetime.now(timezone.utc).isoformat())
    options.as_of = datetime.fromisoformat(clock.replace("Z", "+00:00"))
    if options.as_of.tzinfo is None:
        parser.error("--as-of must include its UTC offset.")
    options.as_of = options.as_of.astimezone(timezone.utc).replace(tzinfo=None)

    from app import create_audit_app
    from models import db
    from sqlalchemy.engine import make_url
    app = create_audit_app()
    url = make_url(app.config["SQLALCHEMY_DATABASE_URI"])
    if url.get_backend_name() != "mysql" or url.host not in {"localhost", "127.0.0.1", "::1"}:
        raise ValueError("Benchmark requires the configured loopback MySQL database.")
    report = {"version": 1, "as_of_utc": options.as_of.isoformat() + "Z", "scope": "local service; not HTTP or browser",
              "phases": "inclusive spans; do not add nested durations", "warmup": options.warmup,
              "max_statement_ms": options.max_statement_ms, "redis_configured": bool(app.config.get("REDIS_URL")), "cases": []}
    try:
        from sqlalchemy import inspect, text
        with app.app_context():
            if set(db.engines) != {None}:
                raise ValueError("Benchmark does not permit additional database binds.")
            report["mysql_version"] = db.session.execute(text("SELECT VERSION()")).scalar()
            if inspect(db.engine).has_table("alembic_version"):
                report["migration_heads"] = list(db.session.execute(text("SELECT version_num FROM alembic_version")).scalars())
            db.session.rollback()
        for case in cases:
            for _ in range(options.warmup):
                sample(app, case, options)
            row = {"name": case["name"], "input_sha256": digest(case), "samples": []}
            report["cases"].append(row)
            for _ in range(options.repeat):
                row["samples"].append(sample(app, case, options))
            times = sorted(value["elapsed_ms"] for value in row["samples"])
            row["elapsed_ms"] = {"min": times[0], "median": statistics.median(times), "p95_sample": times[math.ceil(len(times) * .95) - 1]}
            row["stable_payload"] = (not any("error_type" in value for value in row["samples"])
                                     and len({value["payload_sha256"] for value in row["samples"]}) == 1)
        if previous:
            report["comparison"] = compare_reports(previous, report)
        options.output.parent.mkdir(parents=True, exist_ok=True)
        options.output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    finally:
        with app.app_context():
            db.session.remove()
            db.engine.dispose()
    success = all(case["stable_payload"] for case in report["cases"]) and report.get("comparison", {}).get("equivalent", True)
    print(json.dumps({"output": str(options.output), "cases": len(cases), "successful_and_stable": success}))
    return 0 if success else 1


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as error:
        print(json.dumps({"error_type": type(error).__name__, "message": "Browse baseline failed; SQL/content/credentials omitted."}), file=sys.stderr)
        raise SystemExit(1)
