"""Repository for Deck Access Keys and Redemptions."""

from __future__ import annotations

from datetime import datetime
from typing import Sequence

from models import db
from models.creator_feature_policy import CreatorFeaturePolicy
from models.deck_access_key import DeckAccessKey
from models.deck_access_key_redemption import DeckAccessKeyRedemption


def list_keys_for_deck(
    deck_item_id: str,
    creator_user_id: int | None = None,
) -> list[DeckAccessKey]:
    """Return all access keys created for a specific deck marketplace item."""
    query = DeckAccessKey.query.filter_by(deck_item_id=deck_item_id)
    if creator_user_id is not None:
        query = query.filter_by(creator_user_id=creator_user_id)
    return query.order_by(DeckAccessKey.created_at.desc()).all()


def get_key_by_id(
    key_id: str,
    creator_user_id: int | None = None,
) -> DeckAccessKey | None:
    """Retrieve an access key by ID, optionally verifying creator ownership."""
    query = DeckAccessKey.query.filter_by(id=key_id)
    if creator_user_id is not None:
        query = query.filter_by(creator_user_id=creator_user_id)
    return query.first()


def get_key_by_code(key_code: str) -> DeckAccessKey | None:
    """Find a key by exact code string (trimmed/normalized)."""
    normalized_code = (key_code or "").strip().upper()
    if not normalized_code:
        return None
    return DeckAccessKey.query.filter_by(key_code=normalized_code).first()


def get_key_by_code_locked(key_code: str) -> DeckAccessKey | None:
    """Find a key by code with pessimistic row locking for concurrent redemption safety."""
    normalized_code = (key_code or "").strip().upper()
    if not normalized_code:
        return None
    return DeckAccessKey.query.filter_by(key_code=normalized_code).with_for_update().first()


def count_creator_keys(creator_user_id: int) -> int:
    """Count total keys generated by a creator."""
    return DeckAccessKey.query.filter_by(creator_user_id=creator_user_id).count()


def list_redemptions_for_key(
    key_id: str,
    limit: int = 50,
    offset: int = 0,
) -> list[DeckAccessKeyRedemption]:
    """List redemptions for a specific key."""
    return (
        DeckAccessKeyRedemption.query.filter_by(key_id=key_id)
        .order_by(DeckAccessKeyRedemption.redeemed_at.desc())
        .limit(limit)
        .offset(offset)
        .all()
    )


def count_redemptions_for_key(key_id: str) -> int:
    """Count total redemptions for a key."""
    return DeckAccessKeyRedemption.query.filter_by(key_id=key_id).count()


def get_redemption_by_key_and_user(
    key_id: str,
    user_id: int,
) -> DeckAccessKeyRedemption | None:
    """Check if a specific user has redeemed this key."""
    return DeckAccessKeyRedemption.query.filter_by(key_id=key_id, user_id=user_id).first()


def get_creator_feature_policy(
    feature_code: str = "deck_access_keys",
) -> CreatorFeaturePolicy | None:
    """Get the system policy for a creator feature."""
    return CreatorFeaturePolicy.query.filter_by(feature_code=feature_code).first()
