"""In-memory transactional email provider for unit and integration testing."""

from __future__ import annotations

from datetime import datetime, timezone
from uuid import uuid4

from app.email.address import mask_email
from app.email.constants import DeliveryStatus
from app.email.contracts import EmailConfig, EmailDeliveryResult, RenderedEmailMessage
from app.email.providers.base import BaseEmailProvider

UTC = timezone.utc


class MemoryEmailProvider(BaseEmailProvider):
    """Stores sent messages in memory for test assertions without network access."""

    def __init__(self) -> None:
        self._sent_messages: list[RenderedEmailMessage] = []
        self._deliveries: list[EmailDeliveryResult] = []

    @property
    def provider_name(self) -> str:
        return "memory"

    @property
    def sent_messages(self) -> list[RenderedEmailMessage]:
        """Return a copy of all messages received by this provider."""
        return list(self._sent_messages)

    @property
    def deliveries(self) -> list[EmailDeliveryResult]:
        """Return a copy of all delivery results generated by this provider."""
        return list(self._deliveries)

    def clear(self) -> None:
        """Clear all stored messages and deliveries."""
        self._sent_messages.clear()
        self._deliveries.clear()

    def get_last_message(self) -> RenderedEmailMessage | None:
        """Return the most recently sent message, if any."""
        return self._sent_messages[-1] if self._sent_messages else None

    def send(
        self,
        message: RenderedEmailMessage,
        config: EmailConfig,
    ) -> EmailDeliveryResult:
        """Record message in memory and return successful delivery result."""
        self._sent_messages.append(message)
        now = datetime.now(UTC).replace(tzinfo=None)
        msg_id = f"mem-{uuid4()}"

        result = EmailDeliveryResult(
            success=True,
            status=DeliveryStatus.SENT,
            provider=self.provider_name,
            provider_message_id=msg_id,
            correlation_id=message.correlation_id,
            recipient_masked=mask_email(message.recipient),
            sent_at=now,
            extra={"message_count": len(self._sent_messages)},
        )
        self._deliveries.append(result)
        return result
